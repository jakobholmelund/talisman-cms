// Writes src/admin/themeDefaults.ts from daisyUI's own theme data (daisyui/theme/object), so the
// Theme Builder shows the values of the daisyUI version the site builds with. Run
// `pnpm run theme-defaults` after upgrading daisyUI; `--check` exits with 1 when the file is stale.
//
// daisyUI is not a dependency of this package (sites bring their own), so it is resolved from the
// package first and then from the workspace playground, which builds with it.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const themeDefaultsPath = path.join(packageRoot, 'src/admin/themeDefaults.ts');
const searchRoots = [packageRoot, path.resolve(packageRoot, '../../playground')];

/** Returns daisyUI's themes and theme order, or null when daisyUI is not installed nearby. */
export async function loadDaisyUiThemes() {
  for (const root of searchRoots) {
    let require;
    let packageJsonPath;
    try {
      require = createRequire(path.join(root, 'package.json'));
      packageJsonPath = require.resolve('daisyui/package.json');
    } catch {
      continue;
    }
    const { version } = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
    const load = async (specifier) => (await import(pathToFileURL(require.resolve(specifier)).href)).default;
    return {
      version,
      themes: await load('daisyui/theme/object'),
      order: await load('daisyui/functions/themeOrder'),
    };
  }
  return null;
}

const quote = (value) => JSON.stringify(String(value));

function renderGroup(name, entries) {
  const lines = entries.map(([key, value]) => `      ${quote(key)}: ${quote(value)},`);
  return [`    ${name}: {`, ...lines, '    },'];
}

/** Renders themeDefaults.ts. Theme names follow daisyUI's own order; unlisted themes go last. */
export function renderThemeDefaults({ version, themes, order }) {
  const names = [
    ...order.filter((name) => themes[name]),
    ...Object.keys(themes).filter((name) => !order.includes(name)).sort(),
  ];

  const body = [];
  for (const name of names) {
    const entries = Object.entries(themes[name]);
    const scheme = themes[name]['color-scheme'] === 'dark' ? 'dark' : 'light';
    const colors = entries
      .filter(([key]) => key.startsWith('--color-'))
      .map(([key, value]) => [key.slice('--color-'.length), value]);
    const vars = entries
      .filter(([key]) => key.startsWith('--') && !key.startsWith('--color-'))
      .map(([key, value]) => [key.slice(2), value]);
    body.push(
      `  ${quote(name)}: {`,
      `    colorScheme: ${quote(scheme)},`,
      ...renderGroup('colors', colors),
      ...renderGroup('vars', vars),
      '  },',
    );
  }

  return `// Generated by scripts/theme-defaults.mjs from daisyui@${version} (daisyui/theme/object). Do not edit;
// run \`pnpm run theme-defaults\` after upgrading daisyUI. The values come from daisyUI, which is MIT
// licensed, Copyright (c) 2020 Pouya Saadeghi; see NOTICE.

export interface DaisyUiThemeDefaults {
  colorScheme: 'light' | 'dark';
  /** \`--color-<key>\` values, keyed without the \`--color-\` prefix. */
  colors: Record<string, string>;
  /** Radius, size, border, depth and noise variables, keyed without the leading \`--\`. */
  vars: Record<string, string>;
}

/** The daisyUI release these values were generated from. */
export const DAISYUI_THEME_DEFAULTS_VERSION = ${quote(version)};

/** daisyUI's built-in themes, in daisyUI's own order. */
export const DAISYUI_THEME_DEFAULTS: Record<string, DaisyUiThemeDefaults> = {
${body.join('\n')}
};
`;
}

async function main() {
  const daisyUi = await loadDaisyUiThemes();
  if (!daisyUi) {
    console.error(`daisyUI is not installed in ${searchRoots.join(' or ')}; run pnpm install first.`);
    process.exit(1);
  }

  const source = renderThemeDefaults(daisyUi);
  const relativePath = path.relative(packageRoot, themeDefaultsPath);
  if (process.argv.includes('--check')) {
    if (readFileSync(themeDefaultsPath, 'utf8') !== source) {
      console.error(`${relativePath} does not match daisyui@${daisyUi.version}; run pnpm run theme-defaults.`);
      process.exit(1);
    }
    console.log(`${relativePath} matches daisyui@${daisyUi.version}.`);
    return;
  }

  writeFileSync(themeDefaultsPath, source);
  console.log(`Wrote ${relativePath} from daisyui@${daisyUi.version}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await main();
}
